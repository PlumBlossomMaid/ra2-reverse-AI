// 方向为零向量时返回 0.0（0x59B9D6 加载的是 [0x7E1748] = 0.0f）
TEST(BlobRegion, ZeroDirectionReturnsZero) {
  ra2::rmg::FpuChopScope guard;
  const Rect r{1, 2, 3, 4};
  EXPECT_EQ(DirectionalCost(CellCoord{5, 7}, CellCoord{3, 3}, r, CellCoord{3, 3}, 1.0f, 1.0f, kFull),
            0.0);
}

// 方向分量用算术右移：负数向 −∞ 取整，与"除以 2 向零取整"不是一回事。
// 取一对能把两者区分开的坐标，确认我们走的是前者。
TEST(BlobRegion, DirectionUsesArithmeticShiftNotTruncatingDivide) {
  ra2::rmg::FpuChopScope guard;
  const Rect r{1, 2, 3, 4};
  // n.x-n.y = -3：算术右移得 -2，向零取整得 -1
  const double got = DirectionalCost(CellCoord{0, 0}, CellCoord{-1, 2}, r, CellCoord{0, 0}, 1.0f, 1.0f, kFull);
  const int ax_shift = std::abs((-1 - 2) >> 1);          // |-2| = 2
  const int ax_trunc = std::abs((-1 - 2) / 2);           // |-1| = 1
  EXPECT_NE(ax_shift, ax_trunc);                          // 这组坐标确实能区分
  EXPECT_GT(got, 0.0);
}

