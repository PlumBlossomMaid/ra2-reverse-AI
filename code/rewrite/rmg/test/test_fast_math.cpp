// 缓存的第二个偏差决定随机数流的消耗节奏，漏掉就会整张地图偏移
TEST(NormalDeviate, CachesSecondValue) {
  FpuChopScope fpu;
  Randomizer rng(11584u);
  NormalDeviate gauss(rng);
  EXPECT_FALSE(gauss.has_cached());
  gauss();
  EXPECT_TRUE(gauss.has_cached());
  gauss();
  EXPECT_FALSE(gauss.has_cached());
}

