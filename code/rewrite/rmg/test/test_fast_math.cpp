// 查表只有 14 位精度，与 std::sqrt 系统性不等——这条断言防止有人"优化"掉它
TEST(FastSqrt, DeliberatelyDiffersFromStdSqrt) {
  FpuChopScope fpu;
  EXPECT_NE(FastSqrt(2.0), 1.4142135623730951);
  EXPECT_NEAR(FastSqrt(2.0), 1.4142135623730951, 1e-6);
}

