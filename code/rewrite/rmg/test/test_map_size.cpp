TEST(MapSize, MatchesOriginalOverFullGrid) {
  ra2::rmg::FpuChopScope chop;
  for (const Case& c : kGolden) {
    ra2::rmg::MapSize got = ra2::rmg::ComputeMapSize(c.width_step, c.height_step,
                                                     c.players, c.map_type);
    EXPECT_EQ(got.width, c.width)
        << "P=" << c.players << " MapType=" << c.map_type
        << " Width=" << c.width_step;
    EXPECT_EQ(got.height, c.height)
        << "P=" << c.players << " MapType=" << c.map_type
        << " Height=" << c.height_step;
  }
}

// 逐步舍入不可省：精确有理数算 70*(1-1.2)+80*1.2 得 82，原版给 81。
TEST(MapSize, ClampedHeightTruncatesTo81NotRoundsTo82) {
  ra2::rmg::FpuChopScope chop;
  EXPECT_EQ(ra2::rmg::ComputeMapSize(0, 4, 2, 1).height, 81);
  EXPECT_EQ(ra2::rmg::ComputeMapSize(4, 0, 2, 1).width, 81);
}

// MapType 3/4 跳过 1.2 夹取，插值变外推，地图能比表里的 Hi 还大。
TEST(MapSize, MapType34SkipsClampAndExtrapolates) {
  ra2::rmg::FpuChopScope chop;
  const int expect[] = {80, 83, 86, 90};  // 档位 3/4/5/6
  for (int i = 0; i < 4; ++i) {
    EXPECT_EQ(ra2::rmg::ComputeMapSize(3 + i, 0, 2, 3).width, expect[i]);
    EXPECT_EQ(ra2::rmg::ComputeMapSize(3 + i, 0, 2, 1).width, i == 0 ? 80 : 81);
  }
}

